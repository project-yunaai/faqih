// Use Puppeteer-style approach via existing CDP connection
const puppeteer = require('puppeteer')

app.post('/api/generate', async (req, res) => {
  let browser = null
  
  try {
    const { prompt, ratio = '1:1' } = req.body
    if (!prompt?.trim()) return res.status(400).json({ error: 'Prompt required' })
    
    // Connect to existing Chrome running on port 9222
    browser = await puppeteer.connect({
      browserWSEndpoint: 'ws://127.0.0.1:9222'
    }).catch(async () => {
      console.log('[API] Connecting to fresh Chrome...')
      // If not connected, start one
      browser = await puppeteer.launch({
        headless: false,
        userDataDir: 'C:\\Users\\ASUS\\OneDrive\\Documents\\Default Project\\.chrome-profile',
        executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'
      })
    })
    
    const page = await browser.newPage()
    await page.setViewport({ width: 1280, height: 800 })
    
    // Navigate to Gemini
    await page.goto('https://gemini.google.com/app', { waitUntil: 'domcontentloaded', timeout: 60000 })
    
    // Wait for input box to appear
    await page.waitForSelector('[role="textbox"]', { timeout: 30000 })
    
    // Fill prompt
    await page.fill('[role="textbox"]', `${prompt}. Aspect ratio ${ratio}, high quality, detailed rendering`)
    
    // Press Enter
    await page.keyboard.press('Enter')
    
    console.log(`[API] Sent prompt: ${prompt}`)
    
    // Wait for response (up to 2 minutes)
    try {
      await page.waitForFunction(() => {
        return document.querySelectorAll('img').length > 0
      }, { timeout: 120000 })
    } catch {
      // Continue anyway
    }
    
    // Get first generated image
    const images = await page.$$('img:not([src^="data:"])')
    
    if (images.length === 0) {
      throw new Error('No image generated by Gemini')
    }
    
    // Screenshot the image
    const imgElement = images[0]
    const screenshot = await imgElement.screenshot({ encoding: 'base64' })
    
    res.json({ success: true, data: { url: `data:image/png;base64,${screenshot}`, prompt, ratio } })
    
  } catch (error) {
    console.error('[API] Error:', error.message)
    res.status(500).json({ error: error.message, details: error.stack })
  } finally {
    if (browser) {
      await browser.close().catch(() => {})
    }
  }
})

app.listen(PORT, () => console.log(`[SERVER] Running on http://localhost:${PORT}`))

