const express = require('express')
const axios = require('axios')
const fs = require('fs')
const path = require('path')
const cors = require('cors')
const { spawn } = require('child_process')

const app = express()
app.use(cors())
app.use(express.json({ limit: '50mb' }))

// Load cookies from file
const loadCookies = () => {
  const cookiePath = path.join(__dirname, 'gemini-cookies.json')
  const data = JSON.parse(fs.readFileSync(cookiePath, 'utf8'))
  
  const cookiesHeader = data.cookies.map(c => `${c.name}=${c.value}`).join('; ')
  return { raw: data.cookies, header: cookiesHeader }
}

const PORT = 3001
let cachedCookies = null

async function getCachedCookies() {
  if (!cachedCookies) {
    cachedCookies = loadCookies()
    console.log(`[API] Loaded ${cachedCookies.raw.length} cookies`)
  }
  return cachedCookies
}

// Health check
app.get('/api/health', async (_req, res) => {
  try {
    const cookies = await getCachedCookies()
    res.json({ 
      status: 'ok', 
      savedCookies: cookies.raw.length,
      isAuthenticated: !!cookies.header
    })
  } catch (error) {
    res.status(500).json({ status: 'error', error: error.message })
  }
})

